export function socialPostTemplate():string{
  return `HOOK:
Open with the audience problem, tension, or question that makes the intended reader stop and understand why the topic matters.

VALUE:
1. State the first practical point the audience can act on.
2. State the second practical point, backed by the supplied evidence where available.
3. State the third practical point and connect it to the broader objective.

PROOF:
Use only verified source material or explicitly state that evidence is unavailable. Never invent a result, metric, client claim, or performance outcome.

CTA:
State the single next action the audience should take.`;
}
export function blogOutlineTemplate():string{
  return `TITLE:
Create a clear, search-intent-aligned working title that accurately reflects the documented topic.

SEARCH INTENT:
Record the observed intent as informational, commercial, navigational, transactional, or UNKNOWN.

H1:
Use the primary topic as the main heading without adding unsupported claims.

H2:
- Define the problem and why it matters.
- Explain the evidence-backed approach.
- Provide practical examples that can be verified or clearly labelled illustrative.
- Explain implementation steps and decision points.

CTA:
State one concrete next action for the reader.

SOURCES:
List the actual source URLs or source references used by the draft. If none are available, state UNKNOWN.`;
}
